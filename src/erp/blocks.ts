/** Prefixo mais longo, limitado ao segmento; desconhecido nunca herda Base. */
export function erpBlockOf(path: string): ErpBlock | null {
  return prefixes.find(p => path === p.path || path.startsWith(p.path + "/"))?.block ?? null;
}
